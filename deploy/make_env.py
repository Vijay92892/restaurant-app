#!/usr/bin/env python3
"""Create the production configuration for deploy/docker-compose.yml, once, with fresh secrets.

    python3 make_env.py --domain order.example.in --email you@example.in

Writes three files next to this script (readable by the owner only):
  .env         domain, certificate email, database and Redis passwords (compose variables)
  api.env      the API's settings
  migrate.env  the schema owner's database URL (used by migrations only)
Then fill in the SMTP_* lines in api.env (the API refuses to start without a mail server).

It never overwrites existing files: replacing PIN_ENC_KEY would make every stored table PIN
unreadable, and replacing JWT_SECRET signs every device out. Keep a copy of these files in
your password manager. Standard library only (runs with the server's python3).
"""

from __future__ import annotations

import argparse
import os
import re
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOMAIN = re.compile(r"^(?=.{4,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
# Must match the network in docker-compose.yml: only the Caddy container's hop is trusted.
DOCKER_SUBNET = "172.30.0.0/24"


def secret() -> str:
    return secrets.token_urlsafe(48)  # URL-safe: also usable inside connection URLs


def password() -> str:
    return secrets.token_urlsafe(32)


def render(domain: str, email: str) -> dict[str, str]:
    admin, owner, app, redis = password(), password(), password(), password()
    compose = f"""# Compose variables (docker-compose.yml). Generated by make_env.py — keep secret.
ORDER_DOMAIN={domain}
ACME_EMAIL={email}
POSTGRES_ADMIN_PASSWORD={admin}
DB_OWNER_PASSWORD={owner}
DB_APP_PASSWORD={app}
REDIS_PASSWORD={redis}
"""
    api = f"""# API settings (backend/app/core/config.py). Generated by make_env.py — keep secret.
ENV=production
LOG_LEVEL=INFO

# Runtime role: not a superuser, no BYPASSRLS, owns no tables (checked at startup).
DATABASE_URL=postgresql+asyncpg://restaurant_app:{app}@db:5432/restaurant
APP_DB_ROLE=restaurant_app

# Never change these once the API has run: PIN_ENC_KEY encrypts the stored table PINs and
# JWT_SECRET signs every staff session.
JWT_SECRET={secret()}
PIN_HMAC_KEY={secret()}
PIN_ENC_KEY={secret()}

RATE_LIMIT_BACKEND=redis
EVENT_BUS_BACKEND=redis
REDIS_URL=redis://:{redis}@redis:6379/0

# One origin for the ordering page, the API and the staff app (API_BASE_URL=https://{domain}/api/v1).
PUBLIC_ORDER_BASE_URL=https://{domain}
PUBLIC_WEB_ORIGINS=https://{domain}
PASSWORD_RESET_URL=https://{domain}/reset-password
TRUSTED_PROXIES={DOCKER_SUBNET}

# Restaurants are created by the operator (python -m app.cli create-restaurant).
REGISTRATION_MODE=closed

MEDIA_ROOT=/var/lib/restaurant/media

# Password-reset emails. Required: fill these in (any SMTP provider; port 587 with STARTTLS).
MAIL_BACKEND=smtp
MAIL_FROM=no-reply@{domain}
SMTP_HOST=
SMTP_PORT=587
SMTP_USERNAME=
SMTP_PASSWORD=
"""
    migrate = f"""# Schema owner, for `alembic upgrade head` only. From make_env.py — keep secret.
MIGRATION_DATABASE_URL=postgresql+asyncpg://restaurant_owner:{owner}@db:5432/restaurant
"""
    return {".env": compose, "api.env": api, "migrate.env": migrate}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "--domain", required=True, help="e.g. order.example.in (DNS must point here)"
    )
    parser.add_argument("--email", required=True, help="for Let's Encrypt expiry notices")
    parser.add_argument("--out", type=Path, default=HERE, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    domain = args.domain.strip().lower().removeprefix("https://").rstrip("/")
    if not DOMAIN.fullmatch(domain):
        print(f"Error: {args.domain!r} is not a domain name like order.example.in", file=sys.stderr)
        return 1
    if not EMAIL.fullmatch(args.email.strip()):
        print(f"Error: {args.email!r} is not an email address", file=sys.stderr)
        return 1
    files = render(domain, args.email.strip())
    existing = [name for name in files if (args.out / name).exists()]
    if existing:
        print(
            f"Error: {', '.join(existing)} already exist{'s' if len(existing) == 1 else ''} in "
            f"{args.out}. Nothing was changed (new secrets would break the running system).",
            file=sys.stderr,
        )
        return 1
    for name, text in files.items():
        path = args.out / name
        # Created owner-only from the start: no moment where the secrets are world-readable.
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    print(f"Wrote {', '.join(files)} in {args.out}.")
    print("Next: fill in SMTP_HOST, SMTP_USERNAME and SMTP_PASSWORD in api.env, then")
    print("      docker compose up -d --build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
